/** Human label for a status code in the current UI language (falls back to the code with spaces). */
export function ttStatus(code: string | null | undefined): string {
  if (!code) return '';
  const hit = S[code];
  if (!hit) return code.replace(/_/g, ' ');
  const lang = useUiLang.getState().lang;
  return hit[lang === 'th' ? 1 : lang === 'zh' ? 2 : 0];
}

export function tt(en: string): string {
  const lang = useUiLang.getState().lang;
  if (lang === 'en') return en;
  const hit = D[en] ?? D[en.trim()];
  return hit ? hit[lang === 'th' ? 0 : 1] : en;
}
