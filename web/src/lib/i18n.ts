export type KioskKey = keyof typeof KIOSK_STRINGS;
export type Overrides = Partial<Record<Lang, Record<string, string>>>;

export function makeT(lang: Lang, overrides: Overrides = {}) {
  return (key: KioskKey, vars?: Record<string, string | number>) => {
    let s = overrides[lang]?.[key] || (KIOSK_STRINGS[key] as any)?.[lang] || (KIOSK_STRINGS[key] as any)?.en || key;
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
    return s;
  };
}
export type TFn = ReturnType<typeof makeT>;

